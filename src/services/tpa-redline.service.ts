export async function buildRedlineDocx(args: {
  header: RedlineReviewHeader;
  findings: RedlineFinding[];
}): Promise<{ buffer: Buffer; fileName: string }> {
  const sortedFindings = [...args.findings].sort((a, b) => a.displayOrder - b.displayOrder);

  const children: (Paragraph | Table)[] = [];
  children.push(...makeHeader(args.header));
  sortedFindings.forEach((f, i) => {
    children.push(...makeFindingSection(f, i));
  });

  // Footer-ish closing paragraph
  children.push(
    new Paragraph({
      pageBreakBefore: true,
      alignment: AlignmentType.CENTER,
      spacing: { before: 240, after: 120 },
      children: [
        new TextRun({
          text: 'This redline reflects ADNOC\'s position on the above clauses. We look forward to your response.',
          italics: true,
          size: 20,
          color: COLOR.gray,
        }),
      ],
    }),
  );
  children.push(
    new Paragraph({
      alignment: AlignmentType.CENTER,
      children: [
        new TextRun({
          text: 'ADNOC Legal Affairs Division',
          bold: true,
          size: 22,
          color: COLOR.black,
        }),
      ],
    }),
  );

  const doc = new Document({
    creator: 'ADNOC Musanad Contracts Hub',
    title: `Redline — ${args.header.referenceCode}`,
    description: `Third-party agreement redline against ${args.header.playbookNameEn ?? 'ADNOC playbook'}`,
    sections: [
      {
        properties: {},
        children,
      },
    ],
  });

  const buffer = await Packer.toBuffer(doc);
  const safeName =
    `Redline_${args.header.referenceCode}_${args.header.counterpartyName}`
      .replace(/[^a-zA-Z0-9_-]+/g, '_')
      .slice(0, 80) + '.docx';
  return { buffer, fileName: safeName };
}
